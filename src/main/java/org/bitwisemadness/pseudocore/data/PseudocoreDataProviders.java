package org.bitwisemadness.pseudocore.data;

import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.repository.Pack;
import net.minecraft.server.packs.repository.PackSource;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.data.event.GatherDataEvent;
import net.neoforged.neoforge.event.AddPackFindersEvent;
import org.bitwisemadness.pseudocore.Pseudocore;

/**
 * The datapack's single source of truth (#116): every data file this mod
 * ships comes from the providers registered here, regenerated by
 * {@code ./gradlew runData} into {@code src/generated/resources} and
 * drift-gated in CI - never hand-authored under {@code src/main/resources}.
 *
 * <p>The data run passes {@code --mod pseudocore}, so NeoForge fires this
 * event only for this mod: the dev-run classpath carries Tensura and Ice
 * and Fire (their items resolve during generation), but their own providers
 * never fire here and write nothing into this repo's output tree.</p>
 */
@EventBusSubscriber(modid = Pseudocore.MOD_ID)
public final class PseudocoreDataProviders {

    private PseudocoreDataProviders() {
    }

    @SubscribeEvent
    public static void onGatherData(GatherDataEvent event) {
        if (!event.includeServer()) {
            return;
        }
        var generator = event.getGenerator();
        generator.addProvider(true,
                new PseudocoreRecipeProvider(generator.getPackOutput(), event.getLookupProvider()));
        generator.addProvider(true,
                new PseudocoreItemTagsProvider(generator.getPackOutput(), event.getLookupProvider(),
                        event.getExistingFileHelper()));
        generator.addProvider(true,
                new PseudocoreOptionalPacksProvider(generator.getPackOutput()));
    }

    /**
     * The three optional upgrade-progression packs (#154), registered
     * from their generated folder in the jar: default-off, toggleable
     * per world, TOP-positioned so an enabled pack's stubs override the
     * real recipes.
     */
    @SubscribeEvent
    public static void onAddPackFinders(AddPackFindersEvent event) {
        if (event.getPackType() != PackType.SERVER_DATA) {
            return;
        }
        for (PseudocoreOptionalPacksProvider.PackSpec pack : PseudocoreOptionalPacksProvider.PACKS) {
            event.addPackFinders(
                    ResourceLocation.fromNamespaceAndPath(Pseudocore.MOD_ID,
                            "optional_packs/" + pack.path()),
                    PackType.SERVER_DATA,
                    Component.literal(pack.display()),
                    PackSource.FEATURE,
                    false,
                    Pack.Position.TOP);
        }
    }
}
